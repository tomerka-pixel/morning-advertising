function buildPrompt(b) {
  const biz = b.business || {};
  const yn = v => v ? 'כן' : 'לא';
  return `כתוב ${b.type === 'ad' ? 'טקסט למודעה' : 'פוסט'} לפי המאפיינים הבאים:
- עסק: ${biz.name || ''} — ${biz.field || ''}, ${biz.city || ''}. אופי: ${biz.vibe || ''}. אתר: ${biz.website || ''}
- מטרה: ${b.goal || 'לא צוין'}
- טון: ${b.tone || 'לא צוין'}
- מסגרת כתיבה: ${b.framework || 'AIDA'}
- פלטפורמת יעד: ${b.platform || 'אינסטגרם'}
- קהל יעד: ${b.audience || 'קהל רחב'}
- הצעה / הטבה: ${b.offer || 'אין הצעה ספציפית'}
- קריאה לפעולה: ${b.cta || 'קביעת שיעור היכרות'}
- אורך: ${b.length || 'בינוני'}
- כמות אימוג'י: ${b.emoji || 'מדוד'}${b.type === 'ad' ? '' : '\n- האשטאגים: ' + yn(b.hashtags)}
- הנחיות נוספות: ${b.extra || 'אין'}`;
}

/* CORS: מתירים לאתר ה-GitHub Pages (וכל מקור, כי אין כאן מידע רגיש; ההגנה היא על המפתחות) */
function cors(res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, GET, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, x-access-code');
}

/* הגנת קוד גישה: אם הוגדר ACCESS_CODE בשרת, רק בקשה עם הכותרת התואמת מורשית לייצר.
   אם לא הוגדר — פתוח (למצב מקומי). מחזיר true אם מותר, אחרת כותב 403 ומחזיר false. */
function guard(req, res) {
  const expected = (process['env'] || {}).ACCESS_CODE;
  if (!expected) return true;
  const got = req.headers['x-access-code'] || '';
  if (got === expected) return true;
  res.status(403).json({ error: 'קוד גישה שגוי או חסר. היצירה מותרת רק מהמחשב שלך.' });
  return false;
}

function readBody(req) {
  return new Promise((resolve) => {
    if (req.body) return resolve(typeof req.body === 'string' ? JSON.parse(req.body || '{}') : req.body);
    let data = '';
    req.on('data', c => { data += c; if (data.length > 1e6) req.destroy(); });
    req.on('end', () => { try { resolve(JSON.parse(data || '{}')); } catch { resolve({}); } });
  });
}

